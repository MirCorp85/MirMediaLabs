_manifest = {"mtime": None, "data": {}}


def manifest():
    """{"h3/camera/dolly_in": {"poster": "fx/h3/camera/dolly_in.jpg", "video": "fx/…mp4"}} — reloaded on change."""
    path = os.path.join(FX_DIR, "manifest.json")
    try:
        mt = os.path.getmtime(path)
        if mt != _manifest["mtime"]:
            with open(path, encoding="utf-8") as f:
                _manifest.update(mtime=mt, data=json.load(f))
    except OSError:                                 # compiled build: static/ is embedded in the binary
        if _manifest["mtime"] != "asset":
            try:
                import core
                raw = core.asset("fx/manifest.json")
                _manifest.update(mtime="asset", data=json.loads(raw) if raw else {})
            except Exception:
                _manifest.update(mtime="asset", data={})
    except ValueError:
        _manifest.update(mtime=None, data={})
    return _manifest["data"]


def _doc(model, k):
    base, own = COMMON.get(k) or {}, DOCS.get(model, {}).get(k) or {}
    d = dict(base, **{x: y for x, y in own.items() if x != "opts"})
    d["opts"] = dict(base.get("opts") or {})
    for v, od in (own.get("opts") or {}).items():
        d["opts"][v] = dict(d["opts"].get(v) or {}, **od)
    return d


def apply(model, field):
    """A copy of the field with docs + previews merged in. Original label is kept as `tech` when renamed."""
    d = _doc(model, field["k"])
    if not d.get("desc") and not d.get("label") and not d.get("opts") and "advanced" not in d:
        return field
    f = dict(field)
    if d.get("label") and d["label"] != f.get("label"):
        f["tech"] = d.get("tech") or f.get("label")
        f["label"] = d["label"]
    elif d.get("tech"):
        f["tech"] = d["tech"]
    if d.get("desc"):
        f["desc"] = d["desc"]
    if d.get("group"):
        f["group"] = d["group"]
    if d.get("advanced"):
        f["advanced"] = True
        f["group"] = ADVANCED       # old apps also show it in its own (last) group
    man = manifest()
    if f.get("type") == "select":
        opts, odesc, oprev = [], {}, {}
        for o in f.get("opts") or []:
            v, lab = (o[0], o[1]) if isinstance(o, list) else (o, o)
            od = d["opts"].get(str(v)) or {}
            tech = od.get("tech") or (lab if od.get("label") and od["label"] != lab else "")
            if od.get("label"):
                lab = od["label"] + (" · " + tech if tech else "")
            opts.append([v, lab])
            if od.get("desc"):
                odesc[str(v)] = od["desc"]
            p = man.get("%s/%s/%s" % (model, f["k"], v))
            if p:
                oprev[str(v)] = p
        f["opts"] = opts
        if odesc:
            f["odesc"] = odesc
        if oprev:
            f["opreview"] = oprev
    return f
